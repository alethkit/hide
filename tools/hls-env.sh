# Prints the environment (KEY=VALUE lines) under which Haskell Language Server
# can load hide's own source from inside a running editor; see docs/haskell.md.
#
#   eval "$(tools/hls-env.sh --export)"; hide src/Hide/Sidebar.hs
#   tools/hls-env.sh            # KEY=VALUE lines instead (values may contain spaces)
#
# Run it from an unmodified user environment: it asks cabal where its store,
# configuration and package index live, because an editor session (or a
# sandbox) that relocates XDG_*_HOME hides them from the cabal that HLS starts.
# Nothing is downloaded or installed; it only creates $HIDE_HLS_HOME.
set -eu
home=${HIDE_HLS_HOME:-${TMPDIR:-/tmp}/hide-hls-$(id -u)}
mkdir -p "$home/cache"
store=$(cabal path --store-dir)
config=$(cabal path --config-file)
index=$(cabal path --remote-repo-cache)
{
  if [ -r "$config" ]; then cat "$config"; fi
  printf '\n-- generated by tools/hls-env.sh\nstore-dir: %s\n' "$store"
  if ! grep -q '^remote-repo-cache' "$config" 2>/dev/null; then printf 'remote-repo-cache: %s\n' "$index"; fi
} > "$home/cabal-config"
# hie-bios and ghcide create their caches below XDG_CACHE_HOME, which must be writable.
emit() { if [ "${1:-}" = --export ]; then printf "export %s='%s'\n" "$2" "$3"; else printf '%s=%s\n' "$2" "$3"; fi; }
mode=${1:-}
emit "$mode" XDG_CACHE_HOME "$home/cache"
emit "$mode" CABAL_CONFIG "$home/cabal-config"
# On a ~2 GB machine the editor (~0.6 GB) and the language server (-A128M nursery, ~0.9 GB peak) together exceed memory.
# A smaller allocation area and a compacting old generation, inherited by the whole process tree, make them fit.
emit "$mode" GHCRTS "${HIDE_HLS_RTS:--A16m -c}"
